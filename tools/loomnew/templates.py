RX_MODEL = '''\
"""Pin model for ``firmware/{name}.loom``: the sender that drives its input.

TODO: write this from the protocol's specification, never from the
firmware, and cite the document, section and table for every timing.

As generated by ``tools.loomnew --rx``: :class:`ByteTx` drives start-stop
frames (start bit 0, eight data bits least significant first, stop bit 1,
idle high: the 8N1 frame of ``tools/protomodels/uart.py``) onto one input
pad, and :func:`expected_word` states what the receiver should report for
a frame. A model drives a pad with ``Drive.set`` (push-pull, a ``ui`` or
``uio`` pad) or ``Drive.pull_low`` (open drain, ``uio`` only, for a bus
with a pull-up) in :meth:`drive`, which the bench calls every cycle before
it clocks the chip (``tools/protomodels/bench.py``). Grow these into the
sender of your protocol: change :func:`frame_levels` for its framing and
``bit`` for its rate.
"""

from __future__ import annotations

import collections
from typing import Deque, List, Tuple

from tools.protomodels.bench import Drive, Model, PinSpec, pad_of

DATA_BITS = 8
FRAME_BITS = 1 + DATA_BITS + 1          # start, data, stop
FERR = 0x0100                           # the receiver's framing-error bit


def frame_levels(value: int, stop: int = 1) -> List[int]:
    """The line level of each bit of one frame, in the order sent."""
    data = [(value >> i) & 1 for i in range(DATA_BITS)]
    return [0] + data + [stop]


def expected_word(value: int, stop: int = 1) -> int:
    """What the receiver reports for a frame: the data, and bit 8 if the
    stop bit was 0."""
    return (value & 0xFF) | (0 if stop else FERR)


class ByteTx(Model):
    """Drives frames onto ``pin``; ``bit`` clocks a bit (a float is allowed,
    to model a sender off rate). Bit ``k`` of a frame starting at cycle
    ``t`` begins at ``t + round(k * bit)``. A frame with ``stop=0`` is held
    low for its stop bit, then the line goes high again (idle)."""

    def __init__(self, pin: PinSpec, bit: float) -> None:
        self.pad = pad_of(pin)
        self.bit = float(bit)
        self.level = 1                  # idle high
        self.now = 0                    # the last cycle driven
        self.free = 0                   # first cycle after the last frame
        self._changes: Deque[Tuple[int, int]] = collections.deque()
        self.starts: List[int] = []     # cycle of each start edge

    def send(self, value: int, stop: int = 1, gap: int = 0) -> int:
        """Queue one frame, ``gap`` clocks after the previous one ends (or
        from the next cycle); returns the cycle of its start edge."""
        t = max(self.now + 1, self.free) + gap
        for k, level in enumerate(frame_levels(value, stop)):
            self._changes.append((t + round(k * self.bit), level))
        end = t + round(FRAME_BITS * self.bit)
        self._changes.append((end, 1))
        self.free = end
        self.starts.append(t)
        return t

    def drive(self, drive: Drive, cycle: int) -> None:
        self.now = cycle
        while self._changes and self._changes[0][0] <= cycle:
            self.level = self._changes.popleft()[1]
        drive.set(self.pad, self.level)

    @property
    def done(self) -> bool:
        """Every queued frame is on the line and the line is idle."""
        return not self._changes
'''

