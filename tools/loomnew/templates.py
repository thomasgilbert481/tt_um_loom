MODEL = '''\
"""Reference model for ``firmware/{name}.loom``.

TODO: write this from the protocol's specification, never from the
firmware, and cite the document, section and table for every timing.

As generated by ``tools.loomnew``: :class:`EdgeLog` records the edges of one
pad, and :func:`check_square` states what a square wave of ``periods``
periods with a half period of ``half`` clocks is, edge by edge. Grow these
into the other end of your protocol (a receiver that decodes the pins, or a
device that answers on them) and a checker of the specification's windows.
"""

from __future__ import annotations

from typing import List, Optional, Tuple

from tools.protomodels.bench import Lines, Model, PinSpec, pad_of


class EdgeLog(Model):
    """Every change of one pad, as ``(cycle, new value)``."""

    def __init__(self, pin: PinSpec) -> None:
        self.pad = pad_of(pin)
        self.prev: Optional[int] = None
        self.edges: List[Tuple[int, int]] = []

    def observe(self, lines: Lines) -> None:
        v = lines.get(self.pad)
        if self.prev is not None and v != self.prev:
            self.edges.append((lines.cycle, v))
        self.prev = v


def check_square(edges, half: int, periods: int) -> List[str]:
    """Problems with ``edges`` as a square wave, or ``[]``.

    Expected: ``periods`` rising edges, each followed by a falling edge, the
    first edge rising, and every edge exactly ``half`` clocks after the one
    before it.
    """
    problems = []
    if len(edges) != 2 * periods:
        problems.append("%d edges, expected %d" % (len(edges), 2 * periods))
    for i, (cycle, value) in enumerate(edges):
        if value != (1 if i % 2 == 0 else 0):
            problems.append("edge %d at cycle %d goes to %d" % (i, cycle, value))
    for i in range(1, len(edges)):
        gap = edges[i][0] - edges[i - 1][0]
        if gap != half:
            problems.append("edge %d is %d clocks after edge %d, expected %d"
                            % (i, gap, i - 1, half))
    return problems
'''

